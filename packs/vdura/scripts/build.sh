#!/usr/bin/env bash
# Rebuild the chart archives inside packs/ from pinned upstream sources, then
# write uploadable pack archives (<name>-<version>.tar.gz) to dist/.
#
#   - VDURA charts (csi-panfs, csi-panfs-storageclass) are packaged unchanged
#     from the upstream git tag.
#   - The registry-secret helper chart is packaged from charts-src/.
#   - KMM has no Helm chart upstream, so its config/default kustomization is
#     rendered into charts-src/kernel-module-management/templates and packaged.
#
# Requires: git, helm, kubectl (for kustomize), yq (mikefarah v4), tar
set -euo pipefail

VDURA_CSI_REF=1.2.5
KMM_REF=v2.7.0
# KMM publishes no semver image tags; this is the gcr.io/k8s-staging-kmm build of the v2.7.0 commit.
KMM_IMAGE_TAG=v20260812-v1.0.0-713-g2997771
KMM_STAGING=gcr.io/k8s-staging-kmm

ROOT=$(cd "$(dirname "$0")/.." && pwd)
VDURA_PACK=$ROOT/packs/vdura-panfs-csi-$VDURA_CSI_REF
KMM_PACK=$ROOT/packs/kernel-module-management-${KMM_REF#v}
KMM_CHART=$ROOT/charts-src/kernel-module-management
DIST=$ROOT/dist

for tool in git helm kubectl yq tar; do
  command -v "$tool" >/dev/null || { echo "missing required tool: $tool" >&2; exit 1; }
done

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "==> VDURA PanFS CSI $VDURA_CSI_REF"
git -c advice.detachedHead=false clone -q --depth 1 --branch "$VDURA_CSI_REF" \
  https://github.com/panasasinc/panfs-container-storage-interface-oss "$WORK/vdura"
mkdir -p "$VDURA_PACK/charts"
rm -f "$VDURA_PACK"/charts/*.tgz
helm package "$WORK/vdura/charts/panfs" "$WORK/vdura/charts/storageclass" \
  "$ROOT/charts-src/csi-panfs-registry-secret" -d "$VDURA_PACK/charts"

echo "==> Kernel Module Management $KMM_REF"
git -c advice.detachedHead=false clone -q --depth 1 --branch "$KMM_REF" \
  https://github.com/kubernetes-sigs/kernel-module-management "$WORK/kmm"
kubectl kustomize "$WORK/kmm/config/default" > "$WORK/kmm.yaml"

if grep -q '{{' "$WORK/kmm.yaml"; then
  echo "upstream KMM manifests contain '{{' and would need escaping for Helm" >&2
  exit 1
fi
if [ "$(yq ea '[select(.kind == "Namespace")] | length' "$WORK/kmm.yaml")" != 1 ]; then
  echo "expected exactly one Namespace object in the KMM render" >&2
  exit 1
fi

# Turn the fixed upstream namespace and :latest images into Helm values.
templatize() {
  sed -e 's|kmm-operator-system|{{ .Release.Namespace }}|g' \
      -e "s|$KMM_STAGING/kernel-module-management-operator:latest|{{ .Values.images.operator }}|g" \
      -e "s|$KMM_STAGING/kernel-module-management-webhook-server:latest|{{ .Values.images.webhookServer }}|g" \
      -e "s|$KMM_STAGING/kernel-module-management-worker:latest|{{ .Values.images.worker }}|g" \
      -e "s|$KMM_STAGING/kernel-module-management-signimage:latest|{{ .Values.images.signer }}|g" \
      -e 's|gcr.io/kaniko-project/executor:latest|{{ .Values.images.builder }}|g'
}
HEADER="# Generated by scripts/build.sh from kubernetes-sigs/kernel-module-management $KMM_REF (config/default). Do not edit."

mkdir -p "$KMM_CHART/templates"
rm -f "$KMM_CHART"/templates/*.yaml
{
  echo "$HEADER"
  echo "# CRDs are kept on uninstall so existing Module objects are not deleted with the operator."
  yq 'select(.kind == "CustomResourceDefinition") | .metadata.annotations["helm.sh/resource-policy"] = "keep"' "$WORK/kmm.yaml" | templatize
} > "$KMM_CHART/templates/crds.yaml"
{
  echo "$HEADER"
  echo "# The Namespace object is dropped; Palette creates the pack namespace."
  yq 'select(.kind != "CustomResourceDefinition" and .kind != "Namespace")' "$WORK/kmm.yaml" | templatize
} > "$KMM_CHART/templates/operator.yaml"

leftover=$(grep -n -E 'kmm-operator-system|[[:alnum:].-]+/[[:alnum:]._/-]+:latest' "$KMM_CHART"/templates/*.yaml || true)
if [ -n "$leftover" ]; then
  echo "unexpected upstream values left in KMM templates:" >&2
  echo "$leftover" >&2
  exit 1
fi
grep -q "$KMM_IMAGE_TAG" "$KMM_CHART/values.yaml" || {
  echo "charts-src/kernel-module-management/values.yaml is not pinned to $KMM_IMAGE_TAG" >&2
  exit 1
}

mkdir -p "$KMM_PACK/charts"
rm -f "$KMM_PACK"/charts/*.tgz
helm package "$KMM_CHART" -d "$KMM_PACK/charts"

echo "==> Pack archives"
mkdir -p "$DIST"
for pack in "$VDURA_PACK" "$KMM_PACK"; do
  name=$(yq -r '.name' "$pack/pack.json")
  version=$(yq -r '.version' "$pack/pack.json")
  COPYFILE_DISABLE=1 tar -czf "$DIST/$name-$version.tar.gz" -C "$ROOT/packs" "$(basename "$pack")"
  echo "    dist/$name-$version.tar.gz"
done
